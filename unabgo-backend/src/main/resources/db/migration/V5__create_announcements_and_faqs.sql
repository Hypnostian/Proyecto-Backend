-- Avisos de las dependencias y preguntas frecuentes de Banu (1:N con users).

CREATE TABLE announcements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT       NOT NULL REFERENCES users (id),
    title        VARCHAR(140) NOT NULL,
    body         TEXT         NOT NULL,
    category     VARCHAR(30)  NOT NULL CHECK (category IN ('academico', 'bienestar', 'transporte', 'evento')),
    published_at TIMESTAMP,
    push_sent_at TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_announcements_published ON announcements (published_at);

CREATE TABLE faqs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT       NOT NULL REFERENCES users (id),
    question   VARCHAR(200) NOT NULL,
    keywords   TEXT         NOT NULL,
    answer     TEXT         NOT NULL,
    source_url VARCHAR(300) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP    NOT NULL
);
