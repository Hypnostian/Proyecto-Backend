-- Gestión académica del estudiante: materias, horario, cortes y notas (todas 1:N en cascada).

CREATE TABLE subjects (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(120) NOT NULL,
    credits    SMALLINT     NOT NULL CHECK (credits BETWEEN 0 AND 10),
    teacher    VARCHAR(120),
    color      CHAR(7)      NOT NULL,
    created_at TIMESTAMP    NOT NULL
);
CREATE INDEX idx_subjects_user ON subjects (user_id);

CREATE TABLE schedule_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id  BIGINT   NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  TIME     NOT NULL,
    end_time    TIME     NOT NULL,
    room        VARCHAR(40),
    CHECK (end_time > start_time)
);
CREATE INDEX idx_schedule_blocks_subject ON schedule_blocks (subject_id);

CREATE TABLE grade_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT       NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    name       VARCHAR(60)  NOT NULL,
    weight     NUMERIC(5, 2) NOT NULL CHECK (weight BETWEEN 0 AND 100),
    sort_order SMALLINT     NOT NULL DEFAULT 1
);
CREATE INDEX idx_grade_categories_subject ON grade_categories (subject_id);

CREATE TABLE grade_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT      NOT NULL REFERENCES grade_categories (id) ON DELETE CASCADE,
    name        VARCHAR(80) NOT NULL,
    score       NUMERIC(2, 1) CHECK (score IS NULL OR score BETWEEN 0 AND 5),
    weight      NUMERIC(5, 2) CHECK (weight IS NULL OR weight BETWEEN 0 AND 100),
    graded_at   DATE
);
CREATE INDEX idx_grade_items_category ON grade_items (category_id);
