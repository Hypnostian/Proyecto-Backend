-- Profesores de la UNAB con datos públicos del portal de investigación APOLO (apolo.unab.edu.co).

CREATE TABLE professors (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug      VARCHAR(160) NOT NULL UNIQUE,
    name      VARCHAR(160) NOT NULL,
    title     VARCHAR(500),
    unit      VARCHAR(200),
    unit_url  VARCHAR(300),
    apolo_url VARCHAR(300) NOT NULL UNIQUE,
    cvlac_url VARCHAR(300)
);
CREATE INDEX idx_professors_unit ON professors (unit);
