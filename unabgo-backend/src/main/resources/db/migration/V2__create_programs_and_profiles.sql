-- Oferta académica y perfil del estudiante (relación 1:1 con users).

CREATE TABLE programs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(160) NOT NULL UNIQUE,
    name        VARCHAR(200) NOT NULL,
    faculty     VARCHAR(150) NOT NULL,
    level       VARCHAR(40)  NOT NULL,
    modality    VARCHAR(40),
    price_cop   BIGINT CHECK (price_cop IS NULL OR price_cop >= 0),
    snies       VARCHAR(20),
    url         VARCHAR(300) NOT NULL,
    verified_at TIMESTAMP
);
CREATE INDEX idx_programs_faculty ON programs (faculty);

CREATE TABLE student_profiles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    program_id       BIGINT REFERENCES programs (id) ON DELETE SET NULL,
    student_code     VARCHAR(20) UNIQUE,
    semester         SMALLINT CHECK (semester IS NULL OR semester BETWEEN 1 AND 12),
    language         VARCHAR(5)  NOT NULL DEFAULT 'es',
    reminder_minutes SMALLINT    NOT NULL DEFAULT 30 CHECK (reminder_minutes IN (0, 30, 60))
);
