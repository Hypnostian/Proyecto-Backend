-- Rutas y paradas del bus (N:M con route_stops) y rutas favoritas de cada usuario (N:M con favorite_routes).

CREATE TABLE bus_routes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20) NOT NULL UNIQUE,
    name          VARCHAR(80) NOT NULL,
    color         CHAR(7)     NOT NULL,
    gps_device_id VARCHAR(40) UNIQUE,
    active        BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE bus_stops (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(120)  NOT NULL,
    lat       NUMERIC(9, 6) NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lon       NUMERIC(9, 6) NOT NULL CHECK (lon BETWEEN -180 AND 180),
    is_campus BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE TABLE route_stops (
    route_id   BIGINT   NOT NULL REFERENCES bus_routes (id) ON DELETE CASCADE,
    stop_id    BIGINT   NOT NULL REFERENCES bus_stops (id) ON DELETE CASCADE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (route_id, stop_id)
);

CREATE TABLE favorite_routes (
    user_id    BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    route_id   BIGINT    NOT NULL REFERENCES bus_routes (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, route_id)
);
