-- Planes de estudio de los programas de la UNAB (datos públicos de unab.edu.co): plan 1:N semestres 1:N cursos.
-- Los planes que solo existen como documento (PDF) guardan su texto y no tienen semestres.

CREATE TABLE study_plans (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          VARCHAR(160) NOT NULL UNIQUE,
    program_name  VARCHAR(200) NOT NULL,
    search_name   VARCHAR(220) NOT NULL,
    level         VARCHAR(40),
    structure     VARCHAR(20)  NOT NULL CHECK (structure IN ('semestres', 'texto')),
    total_credits INT CHECK (total_credits IS NULL OR total_credits >= 0),
    plan_url      VARCHAR(1000) NOT NULL,
    source_url    VARCHAR(300) NOT NULL,
    program_id    BIGINT REFERENCES programs (id) ON DELETE SET NULL,
    plan_text     TEXT,
    updated_at    TIMESTAMP    NOT NULL
);
CREATE INDEX idx_study_plans_level ON study_plans (level);
CREATE INDEX idx_study_plans_program ON study_plans (program_id);

CREATE TABLE plan_semesters (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT       NOT NULL REFERENCES study_plans (id) ON DELETE CASCADE,
    number  SMALLINT     NOT NULL,
    name    VARCHAR(80)  NOT NULL,
    credits INT CHECK (credits IS NULL OR credits >= 0)
);
CREATE INDEX idx_plan_semesters_plan ON plan_semesters (plan_id);

CREATE TABLE plan_courses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT       NOT NULL REFERENCES plan_semesters (id) ON DELETE CASCADE,
    name        VARCHAR(200) NOT NULL,
    credits     INT CHECK (credits IS NULL OR credits >= 0),
    sort_order  SMALLINT     NOT NULL DEFAULT 0
);
CREATE INDEX idx_plan_courses_semester ON plan_courses (semester_id);
